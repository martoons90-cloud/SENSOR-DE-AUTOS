/**
 * Convierte un modelo del catálogo argentino a un VehicleProfile activo en la app.
 */
export function createVehicleProfileFromArgentineModel(
  model: ArgentineVehicleModel,
  customPlate?: string,
  customMileage?: number,
  customYear?: number
): VehicleProfile {
  // Determinamos un año realista según la ficha
  const defaultYear = model.years.includes('Presente')
    ? 2022
    : parseInt(model.years.split('-')[1]?.trim() || '2016', 10);

  return {
    id: `veh-${model.id}-${Date.now().toString().slice(-4)}`,
    brand: model.brand,
    model: model.model,
    year: customYear || defaultYear,
    plate: customPlate?.toUpperCase() || generateRandomArgentinePlate(),
    fuelType: model.fuelType,
    currentMileage: customMileage || 48500,
    tankCapacityLiters: model.tankCapacityLiters,
    engineDisplacement: `${model.engineDisplacement} (${model.powerHp} CV)`,
    oilSpec: model.oilSpec,
    tirePressurePsiFront: model.tirePressurePsiFront,
    tirePressurePsiRear: model.tirePressurePsiRear,
    generation: model.generation,
    timingType: model.timingType,
    timingIntervalKm: model.timingIntervalKm,
    gncCompatible: model.gncCompatible,
    obdProtocol: model.obdProtocol,
    typicalWeakPoints: model.typicalWeakPoints,
    maintenanceTips: model.maintenanceTips
  };
}

/**
 * Genera una patente argentina aleatoria realista en formato Mercosur (AA 123 BB)
 * o clásica (ABC 123)
 */
export function generateRandomArgentinePlate(): string {
  const letters = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
  const l1 = letters[Math.floor(Math.random() * letters.length)];
  const l2 = letters[Math.floor(Math.random() * letters.length)];
  const l3 = letters[Math.floor(Math.random() * letters.length)];
  const l4 = letters[Math.floor(Math.random() * letters.length)];
  const n1 = Math.floor(Math.random() * 10);
  const n2 = Math.floor(Math.random() * 10);
  const n3 = Math.floor(Math.random() * 10);

  return `${l1}${l2} ${n1}${n2}${n3} ${l3}${l4}`;
}

/**
 * Busca modelos por texto (marca, modelo, motor, combustible, carrocería).
 */
export function searchArgentineVehicles(query: string, brandFilter?: string, fuelFilter?: string, bodyFilter?: string): ArgentineVehicleModel[] {
  const cleanQ = query.toLowerCase().trim();

  return ARGENTINE_VEHICLES_DATABASE.filter(car => {
    if (brandFilter && brandFilter !== 'all' && car.brand.toLowerCase() !== brandFilter.toLowerCase()) {
      return false;
    }
    if (fuelFilter && fuelFilter !== 'all') {
      if (fuelFilter === 'gnc' && !car.gncCompatible) return false;
      if (fuelFilter !== 'gnc' && car.fuelType !== fuelFilter) return false;
    }
    if (bodyFilter && bodyFilter !== 'all' && car.bodyType.toLowerCase() !== bodyFilter.toLowerCase()) {
      return false;
    }

    if (!cleanQ) return true;

    return (
      car.brand.toLowerCase().includes(cleanQ) ||
      car.model.toLowerCase().includes(cleanQ) ||
      car.engineDisplacement.toLowerCase().includes(cleanQ) ||
      car.years.toLowerCase().includes(cleanQ) ||
      (car.engineCode && car.engineCode.toLowerCase().includes(cleanQ)) ||
      car.oilSpec.toLowerCase().includes(cleanQ) ||
      car.typicalWeakPoints.some(wp => wp.toLowerCase().includes(cleanQ))
    );
  });
}
